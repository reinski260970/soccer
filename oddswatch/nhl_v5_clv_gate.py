"""NHL V5 forecast + chronologically selected CLV entry gate.

Forecast model selection remains outcome-logloss only.
Entry-gate selection is separate and uses ONLY prior-season archive CLV,
never prior-season ROI. Test-season outcomes/closing prices are untouched
until after both model and gate are fixed.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from .nhl_bulk_backtest import SOURCE, _devig_home, load_rows
from .nhl_bulk_v5 import build_rows, _select, _fit, _base, _pred, _blend

OUT = Path("data/hockey/nhl_bulk_v5_clv_gate.json")

EV_THRESHOLDS = (0.03, 0.05, 0.08, 0.12, 0.16)
MAX_ODDS = (1.85, 2.10, 2.40, 2.80, 3.50, 5.00)
MIN_CAL_BETS = 80


def _forecast_season(rows, season):
    """Frozen forecast for one season using only information before that season."""
    choice = _select(rows, season)
    train = [r for r in rows if r["season"] < season]
    test = [r for r in rows if r["season"] == season]
    if choice is None or len(train) < 1000 or not test:
        return [], choice
    model = _fit(choice["C"], train)
    base = _base(train)
    probs = [_blend(p, base, choice["shrink"]) for p in _pred(model, test)]
    out = []
    for r, p in zip(test, probs):
        q = dict(r)
        q["p_home"] = float(p)
        q["model_C"] = choice["C"]
        q["model_shrink"] = choice["shrink"]
        out.append(q)
    return out, choice


def _candidate(row):
    p = row["p_home"]
    eh = p * row["home_open"] - 1
    ea = (1-p) * row["away_open"] - 1
    home = eh >= ea
    return {
        "home": home,
        "ev": eh if home else ea,
        "entry": row["home_open"] if home else row["away_open"],
        "close_prob": (
            _devig_home(row["home_close"], row["away_close"])
            if home else
            1-_devig_home(row["home_close"], row["away_close"])
        ),
        "won": bool(row["target"]) if home else not bool(row["target"]),
    }


def _gate_stats(forecasts, min_ev, max_odds):
    bets = []
    for r in forecasts:
        c = _candidate(r)
        if c["ev"] >= min_ev and c["entry"] <= max_odds:
            bets.append(c)
    if not bets:
        return {
            "bets": 0, "mean_clv": None, "positive_clv_rate": None,
            "profit_units": 0.0, "roi": None,
        }
    clvs = [c["close_prob"] * c["entry"] - 1 for c in bets]
    profit = sum(c["entry"]-1 if c["won"] else -1 for c in bets)
    return {
        "bets": len(bets),
        "mean_clv": sum(clvs)/len(clvs),
        "positive_clv_rate": sum(v > 0 for v in clvs)/len(clvs),
        "profit_units": profit,
        "roi": profit/len(bets),
    }


def _choose_gate(rows, test_season):
    """Gate for season Y is chosen from Y-1 CLV only.

    Y-1 probabilities themselves were generated by a model whose model
    hyperparameters were selected on Y-2. This keeps the gate fully nested.
    """
    calibration, forecast_choice = _forecast_season(rows, test_season-1)
    if not calibration:
        return None
    candidates = []
    for min_ev in EV_THRESHOLDS:
        for max_odds in MAX_ODDS:
            s = _gate_stats(calibration, min_ev, max_odds)
            if s["bets"] < MIN_CAL_BETS or s["mean_clv"] is None:
                continue
            candidates.append((
                s["mean_clv"],
                s["positive_clv_rate"],
                s["bets"],
                -min_ev,       # tie: less aggressive threshold
                max_odds,
                min_ev,
                s,
            ))
    if not candidates:
        return None
    _, _, _, _, max_odds, min_ev, stats = max(
        candidates, key=lambda z: (z[0], z[1], z[2], z[3], -z[4])
    )
    return {
        "min_ev": min_ev,
        "max_odds": max_odds,
        "calibration_season": test_season-1,
        "calibration_forecast_choice": forecast_choice,
        "calibration_bets": stats["bets"],
        "calibration_mean_clv": stats["mean_clv"],
        "calibration_positive_clv_rate": stats["positive_clv_rate"],
        # Release qualification itself is fixed before test season.
        "qualified": (
            stats["mean_clv"] > 0
            and stats["positive_clv_rate"] >= 0.50
            and stats["bets"] >= MIN_CAL_BETS
        ),
    }


def evaluate(rows, season):
    gate = _choose_gate(rows, season)
    forecasts, model_choice = _forecast_season(rows, season)
    if gate is None or not forecasts:
        return {
            "status": "INSUFFICIENT_HISTORY",
            "season": season,
            "gate": gate,
        }
    stats = _gate_stats(forecasts, gate["min_ev"], gate["max_odds"])
    return {
        "status": "EVALUATED",
        "season": season,
        "model_choice": model_choice,
        "gate": gate,
        "test_bets": stats["bets"],
        "test_mean_archive_clv": (
            round(stats["mean_clv"], 6) if stats["mean_clv"] is not None else None
        ),
        "test_positive_clv_rate": (
            round(stats["positive_clv_rate"], 6)
            if stats["positive_clv_rate"] is not None else None
        ),
        "test_profit_units": round(stats["profit_units"], 6),
        "test_roi": round(stats["roi"], 6) if stats["roi"] is not None else None,
    }


def run(path=SOURCE, dest=OUT):
    raw = load_rows(path)
    rows, _, _ = build_rows(raw)
    seasons = sorted({r["season"] for r in rows})
    reports = {str(s): evaluate(rows, s) for s in seasons if s >= 2015}

    evaluated = [r for r in reports.values() if r["status"] == "EVALUATED"]
    qualified = [r for r in evaluated if r["gate"]["qualified"]]
    q_bets = sum(r["test_bets"] for r in qualified)
    q_profit = sum(r["test_profit_units"] for r in qualified)
    q_clv_num = sum(
        r["test_mean_archive_clv"] * r["test_bets"]
        for r in qualified if r["test_mean_archive_clv"] is not None
    )
    q_pos_num = sum(
        r["test_positive_clv_rate"] * r["test_bets"]
        for r in qualified if r["test_positive_clv_rate"] is not None
    )

    result = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "method": "V5 forecast; entry gate selected on prior-season archive CLV only",
        "market_features_used_in_forecast": False,
        "gate_selection_uses_roi": False,
        "gate_grid": {
            "min_ev": list(EV_THRESHOLDS),
            "max_odds": list(MAX_ODDS),
            "min_calibration_bets": MIN_CAL_BETS,
        },
        "release_eligible": False,
        "qualified_test_seasons": len(qualified),
        "qualified_pooled": {
            "bets": q_bets,
            "profit_units": round(q_profit, 3),
            "roi": round(q_profit/q_bets, 6) if q_bets else None,
            "mean_archive_clv": round(q_clv_num/q_bets, 6) if q_bets else None,
            "positive_clv_rate": round(q_pos_num/q_bets, 6) if q_bets else None,
        },
        "season_results": reports,
    }
    Path(dest).write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(result, ensure_ascii=False))
    return result


if __name__ == "__main__":
    run()
